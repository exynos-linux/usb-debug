/*
 * usb-debug console: the bring-up init of exynos-linux device ports, built
 * with the kernel's nolibc, and the same line console as a standalone
 * program for development images (CONSOLE_STDIO, any libc).
 *
 * As the bring-up init (PID 1 of a tiny initramfs):
 *  1. Arms "reboot into Download mode" in the PMU, so any reset (panic, bus
 *     error, watchdog) lands where the host can flash the next build.
 *  2. Prints what the kernel found to the framebuffer console.
 *  3. Forces the USB clock gates on, runs the board's USB preparation,
 *     loads the USB PHY/DWC3 modules and creates a USB NCM network gadget.
 *  4. Serves a tiny line-based debug console on TCP port 23 over IPv6
 *     link-local: dmesg, peek/poke of physical registers, file transfer,
 *     reboot (docs/PROTOCOL.md).
 *  5. If no USB host configures the gadget within the timeout, reboots into
 *     Download mode so the host can flash the next attempt.
 *  6. When it runs because the watchdog reset an OS that U-Boot had already
 *     handed over to, restarts that OS after 15 s, at most twice in a row
 *     (see os_hang_check(); boards with a uniLoader record only).
 *
 * Which SoC and board it runs on comes from the device tree's compatible
 * list (or usbdbg.board=NAME on the command line), matched against the
 * entries compiled in (soc/, boards/). Without a match only the generic
 * parts run: no register is ever written for hardware nobody described.
 */
